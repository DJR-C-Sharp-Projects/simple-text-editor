namespace TextEditor.Core.Enums;

/// <summary>
/// Defines the theme preference used by the application.
/// </summary>
public enum AppTheme
{
    /// <summary>
    /// Follows the theme configured in the operating system.
    /// </summary>
    System,

    /// <summary>
    /// Uses a light interface with light backgrounds and dark text.
    /// </summary>
    Light,

    /// <summary>
    /// Uses a dark interface with dark backgrounds and light text.
    /// </summary>
    Dark
}
